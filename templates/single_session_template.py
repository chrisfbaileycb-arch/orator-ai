from server.routes import handle_routes

class OrchestratorAppHandler(http.server.BaseHTTPRequestHandler):
    def log_message(self, format, *args):
        print(f"[{self.log_date_time_string()}] {format % args}")

    def do_OPTIONS(self):
        self.send_response(204)
        self.send_header("Access-Control-Allow-Origin", "*")
        self.send_header("Access-Control-Allow-Methods", "GET, POST, PUT, DELETE, OPTIONS")
        self.send_header("Access-Control-Allow-Headers", "Content-Type, Authorization")
        self.end_headers()

    def do_GET(self):
        if self.path.startswith("/api/"):
            headers = dict(self.headers)
            status, res = handle_routes(self.path, "GET", headers, {})
            self._send_json(status, res)
        else:
            self._serve_static(self.path)

    def do_POST(self):
        content_length = int(self.headers.get("Content-Length", 0))
        body = {}
        if content_length > 0:
            raw_body = self.rfile.read(content_length)
            try:
                body = json.loads(raw_body.decode())
            except Exception:
                body = {}
        headers = dict(self.headers)
        status, res = handle_routes(self.path, "POST", headers, body)
        self._send_json(status, res)

    def do_DELETE(self):
        headers = dict(self.headers)
        status, res = handle_routes(self.path, "DELETE", headers, {})
        self._send_json(status, res)

    def _send_json(self, status: int, data: dict):
        response_bytes = json.dumps(data).encode("utf-8")
        self.send_response(status)
        self.send_header("Content-Type", "application/json")
        self.send_header("Access-Control-Allow-Origin", "*")
        self.send_header("Content-Length", str(len(response_bytes)))
        self.end_headers()
        self.wfile.write(response_bytes)

    def _serve_static(self, path: str):
        if path == "/" or path == "":
            path = "/index.html"
        clean_path = path.lstrip("/")
        client_dir = os.path.join(os.path.dirname(__file__), "..", "client")
        full_path = os.path.join(client_dir, clean_path)

        if os.path.exists(full_path) and os.path.isfile(full_path):
            mime_type, _ = mimetypes.guess_type(full_path)
            with open(full_path, "rb") as f:
                content = f.read()
            self.send_response(200)
            self.send_header("Content-Type", mime_type or "application/octet-stream")
            self.send_header("Content-Length", str(len(content)))
            self.end_headers()
            self.wfile.write(content)
        else:
            self.send_response(404)
            self.send_header("Content-Type", "text/plain")
            self.end_headers()
            self.wfile.write(b"404 Not Found")

def run():
    init_db()
    port = Config.PORT
    server_address = ("", port)
    socketserver.TCPServer.allow_reuse_address = True
    with socketserver.ThreadingTCPServer(server_address, OrchestratorAppHandler) as httpd:
        print(f"==================================================")
        print(f" {Config.APP_NAME.upper()} AIR-GAPPED APPLIANCE")
        print(f" Server running at: http://localhost:{port}")
        print(f" Zero external network calls. Air-gapped verified.")
        print(f"==================================================")
        httpd.serve_forever()

if __name__ == "__main__":
    run()
