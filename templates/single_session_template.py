def generate_single_session_package(spec):
    project_name = spec.get("name", "orchestrator-app").lower().replace(" ", "-")
    description = spec.get("description", "High-performance air-gapped application generated by The Orchestrator.")
    raw_entities = spec.get("entities", [])
    normalized_entities = []
    if raw_entities:
        for e in raw_entities:
            if isinstance(e, dict):
                normalized_entities.append(e)
            elif isinstance(e, str):
                name = e.split("(")[0].strip() if "(" in e else e.strip()
                fields = [f.strip() for f in e.split("(")[1].rstrip(")").split(",")] if "(" in e else ["id", "data"]
                normalized_entities.append({"name": name, "fields": fields})
    if not normalized_entities:
        normalized_entities = [
            {"name": "User", "fields": ["id", "email", "role", "created_at"]},
            {"name": "Resource", "fields": ["id", "title", "payload", "owner_id", "status", "created_at"]}
        ]
    entities = normalized_entities

    raw_routes = spec.get("routes", [])
    normalized_routes = []
    if raw_routes:
        for r in raw_routes:
            if isinstance(r, dict):
                normalized_routes.append(r)
            elif isinstance(r, str):
                parts = r.split(" ", 1)
                method = parts[0].strip() if len(parts) > 1 else "GET"
                path = parts[1].strip() if len(parts) > 1 else parts[0].strip()
                normalized_routes.append({"method": method, "path": path, "desc": f"Endpoint {method} {path}"})
    if not normalized_routes:
        normalized_routes = [
            {"path": "/api/v1/health", "method": "GET", "desc": "Health check and telemetry"},
            {"path": "/api/v1/auth/login", "method": "POST", "desc": "Air-gapped JWT authentication"},
            {"path": "/api/v1/resources", "method": "GET", "desc": "List user resources with pagination"},
            {"path": "/api/v1/resources", "method": "POST", "desc": "Create signed resource entry"},
            {"path": "/api/v1/resources/{id}", "method": "GET", "desc": "Retrieve resource by ID"},
            {"path": "/api/v1/resources/{id}", "method": "DELETE", "desc": "Hard delete resource"}
        ]
    routes = normalized_routes

    moat = spec.get("moat", "Algorithmic validation engine with zero external SaaS dependencies.")

