# Generates immutable SHA-256 fingerprint verification across ground-truth specs.
import hashlib
import json

class HallmarkVerifier:
    @staticmethod
    def generate_hallmark(spec_dict, file_map):
        spec_bytes = json.dumps(spec_dict, sort_keys=True).encode('utf-8')
        code_bytes = "".join(sorted(file_map.values())).encode('utf-8')
        combined = spec_bytes + b"::" + code_bytes
        return hashlib.sha256(combined).hexdigest()

    @staticmethod
    def audit_contract_integrity(spec_dict, file_map, expected_hallmark):
        computed = HallmarkVerifier.generate_hallmark(spec_dict, file_map)
        return computed == expected_hallmark
